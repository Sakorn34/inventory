        $logAmount = pickup_save_log_amount(isset($_GET['log_amount' . $i]) ? $_GET['log_amount' . $i] : '');

        if ($partId <= 0 || $logProduct === '') {
            throw new RuntimeException('??????????????? ' . $i . ' ??????????');
        }

        $rows[] = array(
            'part_id' => $partId,
            'log_product' => $logProduct,
            'log_amount' => $logAmount,
            'log_remarks' => $logRemarks,
            'pre_id' => $preId,
            'log_date' => $logDate,
            'pre_type' => $preType,
            'log_by' => $logBy,
            'ts_mtn_number' => $tsMtnNumber,
        );
    }

    if (empty($rows)) {
        throw new RuntimeException('??????????????????????????????????????? 1 ??????');
    }

    return array(
        'pre_id' => $preId,
        'rows' => $rows,
    );
}

